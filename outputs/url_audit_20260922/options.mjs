import fs from 'node:fs/promises';
import {Workbook,SpreadsheetFile} from '@oai/artifact-tool';
const dir='outputs/url_audit_20260922';
const rows=JSON.parse(await fs.readFile(`${dir}/options_prices.json`,'utf8'));
const w=Workbook.create(),s=w.worksheets.add('Варіанти кришки');
s.getRange('A1:C13').values=[['URL','SKU','Ціна, грн'],...rows];
s.getRange('A1:C13').format.font={name:'Arial',size:11};
s.getRange('A1:C13').format.rowHeight=25;
s.getRange('A1:C13').format.verticalAlignment='center';
s.getRange('A1:A13').format.columnWidth=84;
s.getRange('B1:B13').format.columnWidth=24;
s.getRange('C1:C13').format.columnWidth=18;
s.getRange('B2:B13').setNumberFormat('@');
s.getRange('C2:C13').setNumberFormat('#,##0.00');
s.tables.add('A1:C13',true,'ProductVariants');
s.getRange('A1:C1').format={fill:'#253E54',font:{name:'Arial',size:11,bold:true,color:'#FFFFFF'},rowHeight:28};
s.freezePanes.freezeRows(1);s.showGridLines=false;
w.recalculate();
console.log((await w.inspect({kind:'table',range:"'Варіанти кришки'!A1:C4",include:'values',tableMaxRows:4,tableMaxCols:3})).ndjson);
await (await SpreadsheetFile.exportXlsx(w)).save(`${dir}/Кришки_Magnum_URL_SKU_ціна.xlsx`);
const p=await w.render({sheetName:s.name,range:'A1:C13',scale:1});
await fs.writeFile(`${dir}/options.png`,new Uint8Array(await p.arrayBuffer()));
