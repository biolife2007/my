import fs from 'node:fs/promises';
import {Workbook,SpreadsheetFile} from '@oai/artifact-tool';
const dir='outputs/url_audit_20260922';
const rows=JSON.parse(await fs.readFile(`${dir}/copper_prices.json`,'utf8'));
const w=Workbook.create(),s=w.worksheets.add('Мідні кришки');
s.getRange('A1:D7').values=[['URL','SKU','Ціна, грн','Розмір'],...rows];
s.getRange('A1:D7').format.font={name:'Arial',size:11};
s.getRange('A1:D7').format.rowHeight=27;
s.getRange('A1:D7').format.verticalAlignment='center';
s.getRange('A1:A7').format.columnWidth=86;
s.getRange('B1:B7').format.columnWidth=24;
s.getRange('C1:C7').format.columnWidth=18;
s.getRange('D1:D7').format.columnWidth=48;
s.getRange('B2:B7').setNumberFormat('@');
s.getRange('C2:C7').setNumberFormat('#,##0.00');
s.tables.add('A1:D7',true,'CopperVariants');
s.getRange('A1:D1').format={fill:'#253E54',font:{name:'Arial',size:11,bold:true,color:'#FFFFFF'},rowHeight:28};
s.getRange('A9').values=[['На сайті SKU COPPER LID 40-3 повторюється у двох URL із різними цінами: 6 400 і 6 650 грн.']];
s.getRange('A9').format.font={name:'Arial',size:10};
s.freezePanes.freezeRows(1);s.showGridLines=false;
w.recalculate();
console.log((await w.inspect({kind:'table',range:"'Мідні кришки'!A1:D7",include:'values',tableMaxRows:7,tableMaxCols:4})).ndjson);
await (await SpreadsheetFile.exportXlsx(w)).save(`${dir}/Мідні_кришки_URL_SKU_ціна_розмір.xlsx`);
const p=await w.render({sheetName:s.name,range:'A1:D9',scale:1});
await fs.writeFile(`${dir}/copper.png`,new Uint8Array(await p.arrayBuffer()));
