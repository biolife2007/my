def clean_text(value: str) -> str:
    value = html.unescape(value)
    value = re.sub(r"\s+", " ", value)
    return value.strip()


def text_to_html(value: str) -> str:
    escaped = html.escape(clean_text(value), quote=False)
    return f"<p>{escaped}</p>" if escaped else ""


def compact_html(value: str) -> str:
    value = re.sub(r">\s+<", "><", value)
    value = re.sub(r"\s+", " ", value)
    return value.strip()


def extract_description_html(raw_html: str) -> str:
    match = re.search(
        r'<div class="tab-pane active" id="tab-description">(.*?)'
        r'\s*<div class="tab-pane" id="tab-specification">',
        raw_html,
        re.S,
    )
    if not match:
        return ""

    fragment = BeautifulSoup(match.group(1), "html.parser")
    for tag in fragment.select("style, script"):
        tag.decompose()

    nested_body = fragment.select_one("body")
    source = nested_body if nested_body else fragment
    return compact_html("".join(str(child) for child in source.contents))


def extract_product_json(soup: BeautifulSoup) -> dict:
    for script in soup.find_all("script", {"type": "application/ld+json"}):
        raw = script.string or script.get_text()
        try:
            data = json.loads(raw)
        except json.JSONDecodeError:
            continue
        if data.get("@type") == "Product":
            return data
    return {}


def normalize_photo(url: str) -> str:
    return url.replace("\\/", "/")


def parse_page(path: Path, url: str) -> dict:
    raw_html = path.read_text(encoding="utf-8")
    soup = BeautifulSoup(raw_html, "html.parser")
    product_json = extract_product_json(soup)

    title_node = soup.select_one("h1.h1-prod-name")
    title = clean_text(title_node.get_text(" ")) if title_node else clean_text(product_json.get("name", ""))

    sku_match = re.search(r"Код товару:\s*<span>.*?([A-Z]\d{4}).*?</span>", str(soup), re.S)
    sku = sku_match.group(1) if sku_match else ""

    price = ""
    offers = product_json.get("offers") or {}
    if isinstance(offers, dict) and offers.get("price") is not None:
        price = str(offers["price"])

    photos = []
    for link in soup.select(".slider-main-img a[href]"):
        href = normalize_photo(link["href"])
        if href.startswith("https://hotrod.ua/image/") and href not in photos:
            photos.append(href)
    for image_url in product_json.get("image", []) or []:
        image_url = normalize_photo(image_url)
        if image_url not in photos:
            photos.append(image_url)

    description_html = extract_description_html(raw_html)

    rewrite = REWRITES.get(sku, {"name": "", "description_html": ""})
    russian = RUSSIAN_REWRITES.get(sku, {"name": "", "description_html": ""})
    return {
        "URL": url,
        "SKU": sku,
        "Назва": title,
        "Опис HTML": description_html,
        "Ціна": price,
        "Фото": ", ".join(photos),
        "Рерайт назви": rewrite["name"],
        "Рерайт опису HTML": rewrite["description_html"],
        "Назва російською": russian["name"],
        "Опис російською HTML": russian["description_html"],
    }


def write_xlsx(rows: list[dict]) -> None:
    wb = Workbook()
    ws = wb.active
    ws.title = "HotRod"

    headers = [
        "URL",
        "SKU",
        "Назва",
        "Опис HTML",
        "Ціна",
        "Фото",
        "Рерайт назви",
        "Рерайт опису HTML",
        "Назва російською",
        "Опис російською HTML",
    ]
    ws.append(headers)

    header_fill = PatternFill("solid", fgColor="D9EAF7")
    for cell in ws[1]:
        cell.font = Font(bold=True)
        cell.fill = header_fill
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)

    for row in rows:
        ws.append([row[key] for key in headers])

    widths = {
        "A": 38,
        "B": 12,
        "C": 42,
        "D": 70,
        "E": 10,
        "F": 78,
        "G": 44,
        "H": 70,
        "I": 44,
        "J": 70,
    }
    for column, width in widths.items():
        ws.column_dimensions[column].width = width

    for row in ws.iter_rows(min_row=2):
        for cell in row:
            cell.alignment = Alignment(vertical="top", wrap_text=True)

    ws.freeze_panes = "A2"
    ws.auto_filter.ref = ws.dimensions
    wb.save(OUTPUT)


